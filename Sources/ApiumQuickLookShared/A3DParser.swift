import Foundation
import ImageIO

/// Apium project containers use 3MF-style settings and thumbnails, with Git
/// version metadata beneath Metadata/.git (the Windows reader's convention).
public struct A3DParser: PreviewParsing {
    public init() {}

    public func parse(url: URL) throws -> PreviewMetadata {
        let archive = try ZipArchiveReader(url: url)
        guard let data = try archive.readFile(named: "Metadata/Slic3r_PE.config") else {
            return PreviewMetadata()
        }
        let text: String
        if data.starts(with: [0xff, 0xfe]) || data.starts(with: [0xfe, 0xff]) {
            text = String(data: data, encoding: .utf16) ?? ""
        } else {
            text = String(data: data, encoding: .utf8) ?? String(data: data, encoding: .isoLatin1) ?? ""
        }
        let values = MetadataHelpers.parseCommentKeyValueLines(from: text, commentOnly: false)
        var metadata = MetadataHelpers.metadata(from: values)
        let lower = text.lowercased()
        let hasApiumKey = values.keys.contains { $0.hasPrefix("apium_") }
        let hasSetting = ["printer_model", "filament_type", "nozzle_diameter", "temperature", "layer_height", "perimeters", "fill_density"]
            .contains { values[$0] != nil }
        metadata.isApiumFile = lower.contains("generated by apiumslicer")
            || lower.contains("apiumslicer_config = begin") || (hasApiumKey && hasSetting)
        metadata.printTime = nil
        let paths = try archive.listPaths(withPrefix: "")
        let candidates = ["Metadata/thumbnail.png", "Metadata/thumbnail.jpg", "Metadata/thumbnail.jpeg",
                          "Metadata/plate_1.png", "Thumbnails/thumbnail.png"]
        let fallback = paths.filter { path in
            let name = path.lowercased()
            return (name.hasPrefix("metadata/") || name.hasPrefix("thumbnails/"))
                && (name.contains("thumbnail") || name.contains("plate_1"))
                && ["png", "jpg", "jpeg"].contains(URL(fileURLWithPath: name).pathExtension)
        }
        if let imageData = try archive.readFirstExistingFile(candidates: candidates + fallback),
           let source = CGImageSourceCreateWithData(imageData as CFData, nil) {
            metadata.previewImage = CGImageSourceCreateImageAtIndex(source, 0, nil)
        }
        metadata.projectVersion = try projectVersion(archive, paths: paths)
        return metadata
    }

    private func projectVersion(_ archive: ZipArchiveReader, paths: [String]) throws -> String {
        let prefix = "metadata/.git/"
        let gitPaths = paths.filter { $0.lowercased().hasPrefix(prefix) }
        guard !gitPaths.isEmpty else { return "Not versioned" }
        let tagPrefix = prefix + "refs/tags/"
        var tags = gitPaths.filter { $0.lowercased().hasPrefix(tagPrefix) }
            .map { String($0.dropFirst(tagPrefix.count)) }
        if let packed = try archive.readFile(named: "Metadata/.git/packed-refs"),
           let text = String(data: packed, encoding: .utf8) {
            for line in text.split(whereSeparator: \.isNewline) where !line.hasPrefix("#") && !line.hasPrefix("^") {
                let fields = line.split(whereSeparator: \.isWhitespace)
                if fields.count == 2, fields[1].hasPrefix("refs/tags/") {
                    tags.append(String(fields[1].dropFirst("refs/tags/".count)))
                }
            }
        }
        // Match Explorer: highest numeric release tag, independent of HEAD.
        let versions = tags.compactMap { tag -> (String, [Int])? in
            let core = tag.first?.lowercased() == "v" ? String(tag.dropFirst()) : tag
            let numeric = core.prefix { $0 != "-" && $0 != "+" && $0 != "_" }
            let parts = numeric.split(separator: ".", omittingEmptySubsequences: false)
            guard (2...3).contains(parts.count), parts.allSatisfy({ !$0.isEmpty && $0.allSatisfy(\.isNumber) }) else { return nil }
            let numbers = parts.compactMap { Int($0) }
            guard numbers.count == parts.count else { return nil }
            return (tag, numbers + Array(repeating: 0, count: 3 - numbers.count))
        }
        return versions.max { lhs, rhs in
            lhs.1 == rhs.1 ? lhs.0 < rhs.0 : lhs.1.lexicographicallyPrecedes(rhs.1)
        }?.0 ?? "Version unknown"
    }
}
