import Foundation
import CoreGraphics
import ImageIO

public struct ThreeMFParser: PreviewParsing {
    public init() {}

    public func parse(url: URL) throws -> PreviewMetadata {
        let archive = try ZipArchiveReader(url: url)

        guard let configData = try archive.readFile(named: "Metadata/Slic3r_PE.config") else {
            return PreviewMetadata(isApiumFile: false)
        }

        let configText = String(data: configData, encoding: .utf8) ?? String(data: configData, encoding: .ascii) ?? ""
        let isApium = configText.lowercased().contains("generated by apiumslicer")

        let kv = MetadataHelpers.parseCommentKeyValueLines(from: configText)

        let thumbnailData = try archive.readFirstExistingFile(candidates: [
            "Metadata/thumbnail.png",
            "Metadata/thumbnail.jpg",
            "Metadata/thumbnail.jpeg",
            "Metadata/Thumbnail.png",
            "thumbnail.png"
        ])

        let image: CGImage?
        if let thumb = thumbnailData, let source = CGImageSourceCreateWithData(thumb as CFData, nil) {
            image = CGImageSourceCreateImageAtIndex(source, 0, nil)
        } else {
            image = nil
        }

        return PreviewMetadata(
            previewImage: image,
            printer: MetadataHelpers.pick(["printer_model", "printer_settings_id", "printer_vendor"], from: kv),
            projectVersion: resolveProjectVersion(in: archive),
            materialType: MetadataHelpers.pick(["filament_type", "filament_settings_id"], from: kv),
            nozzleDiameter: MetadataHelpers.parseNozzleDiameter(from: kv),
            nozzleTemperature: MetadataHelpers.parseNozzleTemperature(from: kv),
            bedTemperature: MetadataHelpers.parseBedTemperature(from: kv),
            layerHeight: MetadataHelpers.parseLayerHeight(from: kv),
            perimeters: MetadataHelpers.parsePerimeters(from: kv),
            infillPattern: MetadataHelpers.parseInfillPattern(from: kv),
            infillDensity: MetadataHelpers.parseInfillDensity(from: kv),
            printTime: nil,
            isApiumFile: isApium
        )
    }

    private func resolveProjectVersion(in archive: ZipArchiveReader) -> String {
        let hasGitMetadata = (try? archive.listPaths(withPrefix: ".git/").isEmpty == false) ?? false
        guard hasGitMetadata else { return "Not versioned" }

        guard let headHash = resolveHeadCommitHash(in: archive) else {
            return "Not versioned"
        }

        let headTags = resolveHeadTags(in: archive, headHash: headHash)
        guard !headTags.isEmpty else {
            return "Version unknown"
        }
        return selectPreferredTag(from: headTags)
    }

    private func resolveHeadCommitHash(in archive: ZipArchiveReader) -> String? {
        guard
            let headData = try? archive.readFile(named: ".git/HEAD"),
            let headText = decodeText(headData)?
                .trimmingCharacters(in: .whitespacesAndNewlines),
            !headText.isEmpty
        else {
            return nil
        }

        if headText.hasPrefix("ref:") {
            let refPath = String(headText.dropFirst("ref:".count))
                .trimmingCharacters(in: .whitespacesAndNewlines)
            guard !refPath.isEmpty else { return nil }

            if let looseRefHash = readHash(in: archive, path: ".git/\(refPath)") {
                return looseRefHash
            }

            return readPackedRefHash(in: archive, refPath: refPath)
        }

        return normalizeHash(headText)
    }

    private func resolveHeadTags(in archive: ZipArchiveReader, headHash: String) -> [String] {
        var tags = Set<String>()

        if let paths = try? archive.listPaths(withPrefix: ".git/refs/tags/") {
            for path in paths {
                guard let hash = readHash(in: archive, path: path), hash == headHash else {
                    continue
                }
                let tagName = String(path.dropFirst(".git/refs/tags/".count))
                if !tagName.isEmpty {
                    tags.insert(tagName)
                }
            }
        }

        for packedRef in readPackedRefs(in: archive) where packedRef.refPath.hasPrefix("refs/tags/") {
            guard packedRef.hash == headHash else { continue }
            let tagName = String(packedRef.refPath.dropFirst("refs/tags/".count))
            if !tagName.isEmpty {
                tags.insert(tagName)
            }
        }

        return Array(tags)
    }

    private func readHash(in archive: ZipArchiveReader, path: String) -> String? {
        guard let data = try? archive.readFile(named: path) else {
            return nil
        }
        return decodeText(data).flatMap(normalizeHash(_:))
    }

    private func readPackedRefHash(in archive: ZipArchiveReader, refPath: String) -> String? {
        for packedRef in readPackedRefs(in: archive) where packedRef.refPath == refPath {
            return packedRef.hash
        }
        return nil
    }

    private func readPackedRefs(in archive: ZipArchiveReader) -> [(hash: String, refPath: String)] {
        guard
            let data = try? archive.readFile(named: ".git/packed-refs"),
            let text = decodeText(data)
        else {
            return []
        }

        var refs: [(hash: String, refPath: String)] = []
        for rawLine in text.split(whereSeparator: \.isNewline) {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            if line.isEmpty || line.hasPrefix("#") || line.hasPrefix("^") {
                continue
            }

            let parts = line.split(maxSplits: 1, omittingEmptySubsequences: true, whereSeparator: \.isWhitespace)
            guard parts.count == 2 else { continue }

            let hashCandidate = String(parts[0])
            let refPath = String(parts[1])
            guard let hash = normalizeHash(hashCandidate), !refPath.isEmpty else {
                continue
            }

            refs.append((hash: hash, refPath: refPath))
        }

        return refs
    }

    private func selectPreferredTag(from tags: [String]) -> String {
        let semverTags = tags.compactMap { tag -> (tag: String, version: [Int])? in
            guard let version = parseSemVer(tag) else { return nil }
            return (tag: tag, version: version)
        }

        if let bestSemVerTag = semverTags.max(by: { lhs, rhs in
            let comparison = compareVersions(lhs.version, rhs.version)
            if comparison != 0 {
                return comparison < 0
            }
            return lhs.tag.localizedCaseInsensitiveCompare(rhs.tag) == .orderedAscending
        }) {
            return bestSemVerTag.tag
        }

        return tags.max(by: { lhs, rhs in
            lhs.localizedCaseInsensitiveCompare(rhs) == .orderedAscending
        }) ?? tags[0]
    }

    private func parseSemVer(_ tag: String) -> [Int]? {
        let trimmed = tag.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        let core = (trimmed.first == "v" || trimmed.first == "V")
            ? String(trimmed.dropFirst())
            : trimmed
        let segments = core.split(separator: ".", omittingEmptySubsequences: false)
        guard !segments.isEmpty, segments.count <= 3 else { return nil }

        var values: [Int] = []
        values.reserveCapacity(3)
        for segment in segments {
            guard !segment.isEmpty, segment.allSatisfy(\.isNumber), let value = Int(segment) else {
                return nil
            }
            values.append(value)
        }
        while values.count < 3 {
            values.append(0)
        }
        return values
    }

    private func compareVersions(_ lhs: [Int], _ rhs: [Int]) -> Int {
        for index in 0..<max(lhs.count, rhs.count) {
            let l = index < lhs.count ? lhs[index] : 0
            let r = index < rhs.count ? rhs[index] : 0
            if l < r { return -1 }
            if l > r { return 1 }
        }
        return 0
    }

    private func decodeText(_ data: Data) -> String? {
        String(data: data, encoding: .utf8)
            ?? String(data: data, encoding: .ascii)
    }

    private func normalizeHash(_ raw: String) -> String? {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !trimmed.isEmpty, trimmed.allSatisfy(\.isHexDigit) else {
            return nil
        }
        return trimmed
    }
}
