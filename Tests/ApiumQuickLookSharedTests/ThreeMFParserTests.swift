import XCTest
@testable import ApiumQuickLookShared

final class ThreeMFParserTests: XCTestCase {
    func testParses3MFApiumMetadataAndThumbnail() throws {
        let metadata = try ThreeMFParser().parse(url: FixturePaths.project3mfURL)

        XCTAssertTrue(metadata.isApiumFile)
        XCTAssertNotNil(metadata.previewImage)
        XCTAssertEqual(metadata.printer, "P220_T0")
        XCTAssertEqual(metadata.projectVersion, "v02.1")
        XCTAssertEqual(metadata.materialType, "PLA")
        XCTAssertEqual(metadata.nozzleDiameter, "0.4")
        XCTAssertNil(metadata.printTime)
    }

    func test3MFWithoutSlic3rConfigIsRejected() throws {
        let tempDir = URL(fileURLWithPath: NSTemporaryDirectory())
        let fake3mf = tempDir.appendingPathComponent("invalid.3mf")
        let data = Data([0x50, 0x4b, 0x05, 0x06] + Array(repeating: 0, count: 18))
        try data.write(to: fake3mf)

        let metadata = try ThreeMFParser().parse(url: fake3mf)
        XCTAssertFalse(metadata.isApiumFile)
    }

    func test3MFWithoutThumbnailReturnsNoImage() throws {
        let base = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent(UUID().uuidString)
        let metadataDir = base.appendingPathComponent("Metadata")
        try FileManager.default.createDirectory(at: metadataDir, withIntermediateDirectories: true)

        let config = metadataDir.appendingPathComponent("Slic3r_PE.config")
        let configText = """
        ; generated by ApiumSlicer 1.1.0
        ; printer_model = P220_T0
        ; filament_type = PLA
        ; nozzle_diameter = 0.4
        """
        try configText.write(to: config, atomically: true, encoding: .utf8)

        let output = base.appendingPathExtension("3mf")
        try runShell("/usr/bin/zip", arguments: ["-q", "-r", output.path, "Metadata"], currentDirectory: base)

        let parsed = try ThreeMFParser().parse(url: output)
        XCTAssertTrue(parsed.isApiumFile)
        XCTAssertNil(parsed.previewImage)
        XCTAssertEqual(parsed.printer, "P220_T0")
        XCTAssertEqual(parsed.projectVersion, "Not versioned")
    }

    func testVersionedProjectWithoutHeadTagReturnsUnknown() throws {
        let hash = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
        let otherHash = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
        let url = try make3MFFixture(gitFiles: [
            ".git/HEAD": "ref: refs/heads/main\n",
            ".git/refs/heads/main": "\(hash)\n",
            ".git/refs/tags/v1.0": "\(otherHash)\n"
        ])

        let metadata = try ThreeMFParser().parse(url: url)
        XCTAssertEqual(metadata.projectVersion, "Version unknown")
    }

    func testVersionedProjectReadsTagFromPackedRefs() throws {
        let hash = "cccccccccccccccccccccccccccccccccccccccc"
        let packedRefs = """
        # pack-refs with: peeled fully-peeled sorted
        \(hash) refs/heads/main
        \(hash) refs/tags/v3.4
        """
        let url = try make3MFFixture(gitFiles: [
            ".git/HEAD": "ref: refs/heads/main\n",
            ".git/packed-refs": packedRefs
        ])

        let metadata = try ThreeMFParser().parse(url: url)
        XCTAssertEqual(metadata.projectVersion, "v3.4")
    }

    func testMultipleHeadTagsPreferHighestSemVer() throws {
        let hash = "dddddddddddddddddddddddddddddddddddddddd"
        let url = try make3MFFixture(gitFiles: [
            ".git/HEAD": "ref: refs/heads/main\n",
            ".git/refs/heads/main": "\(hash)\n",
            ".git/refs/tags/v2.0": "\(hash)\n",
            ".git/refs/tags/v2.1": "\(hash)\n",
            ".git/refs/tags/release": "\(hash)\n"
        ])

        let metadata = try ThreeMFParser().parse(url: url)
        XCTAssertEqual(metadata.projectVersion, "v2.1")
    }

    func testInvalidHeadFallsBackToNotVersioned() throws {
        let url = try make3MFFixture(gitFiles: [
            ".git/HEAD": "not-a-valid-head\n"
        ])

        let metadata = try ThreeMFParser().parse(url: url)
        XCTAssertEqual(metadata.projectVersion, "Not versioned")
    }

    private func runShell(_ executable: String, arguments: [String], currentDirectory: URL) throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: executable)
        process.arguments = arguments
        process.currentDirectoryURL = currentDirectory
        try process.run()
        process.waitUntilExit()

        if process.terminationStatus != 0 {
            XCTFail("Command failed: \(executable) \(arguments.joined(separator: " "))")
        }
    }

    private func make3MFFixture(gitFiles: [String: String]) throws -> URL {
        let base = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: base, withIntermediateDirectories: true)

        let metadataDir = base.appendingPathComponent("Metadata")
        try FileManager.default.createDirectory(at: metadataDir, withIntermediateDirectories: true)

        let config = metadataDir.appendingPathComponent("Slic3r_PE.config")
        let configText = """
        ; generated by ApiumSlicer 1.1.0
        ; printer_model = P220_T0
        ; filament_type = PLA
        ; nozzle_diameter = 0.4
        """
        try configText.write(to: config, atomically: true, encoding: .utf8)

        for (path, contents) in gitFiles {
            let fileURL = base.appendingPathComponent(path)
            let dirURL = fileURL.deletingLastPathComponent()
            try FileManager.default.createDirectory(at: dirURL, withIntermediateDirectories: true)
            try contents.write(to: fileURL, atomically: true, encoding: .utf8)
        }

        let output = base.appendingPathExtension("3mf")
        var zipArgs = ["-q", "-r", output.path, "Metadata"]
        if !gitFiles.isEmpty {
            zipArgs.append(".git")
        }
        try runShell("/usr/bin/zip", arguments: zipArgs, currentDirectory: base)
        return output
    }
}
