    func testOBJNegativeIndicesPolygonAndTransparentRendering() throws {
        let url = temporaryURL(extension: "OBJ")
        try "v 0 0 0\nv 10 0 0\nv 10 20 0\nv 0 20 0\nf -4/1 -3/2 -2/3 -1/4\n".write(to: url, atomically: true, encoding: .utf8)
        let metadata = try PreviewParserFactory.parse(url: url)
        XCTAssertEqual(metadata.mesh?.format, "OBJ")
        XCTAssertEqual(metadata.mesh?.vertexCount, 4)
        XCTAssertEqual(metadata.mesh?.faceCount, 1)
        XCTAssertEqual(metadata.mesh?.triangleCount, 2)
        XCTAssertEqual(metadata.mesh?.dimensions.x, 10)
        XCTAssertEqual(metadata.mesh?.dimensions.y, 20)
        let image = try XCTUnwrap(metadata.previewImage)
        let pixels = try XCTUnwrap(image.dataProvider?.data) as Data
        let alphas = stride(from: 3, to: pixels.count, by: 4).map { pixels[$0] }
        XCTAssertTrue(alphas.contains(0))
        XCTAssertTrue(alphas.contains(255))
    }

    func testBinaryAndASCIISTL() throws {
        var binary = Data(repeating: 0, count: 80)
        binary.append(contentsOf: [1, 0, 0, 0])
        for value: Float in [0, 0, 1, 0, 0, 0, 10, 0, 0, 0, 20, 0] {
            var bits = value.bitPattern.littleEndian
            withUnsafeBytes(of: &bits) { binary.append(contentsOf: $0) }
        }
        binary.append(contentsOf: [0, 0])
        let parser = MeshParser()
        let (mesh, format) = try parser.geometry(data: binary, extension: "stl")
        XCTAssertEqual(format, "STL Binary")
        XCTAssertEqual(mesh.triangles.count, 1)
        let ascii = Data("solid test\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 10 0 0\nvertex 0 20 0\nendloop\nendfacet\nendsolid\n".utf8)
        let (other, otherFormat) = try parser.geometry(data: ascii, extension: "stl")
        XCTAssertEqual(otherFormat, "STL ASCII")
        XCTAssertEqual(other.triangles.count, 1)
        XCTAssertNotNil(MeshRenderer.render(mesh, size: 32))
    }

    func testMalformedMeshesFailWithoutCrashing() throws {
        for text in ["v 0 0 0\nf 1 2 3", "v nan 1 2", "", "v 0 0 0\nf 0 0 0"] {
            XCTAssertThrowsError(try MeshParser().geometry(data: Data(text.utf8), extension: "obj"))
        }
        XCTAssertThrowsError(try MeshParser().geometry(data: Data(repeating: 0xff, count: 84), extension: "stl"))
    }

    func testMalformedZIPBoundsFailWithoutCrashing() throws {
        for bytes in [Data(), Data([0x50, 0x4b, 0x05, 0x06] + Array(repeating: 0xff, count: 18))] {
            let url = temporaryURL(extension: "a3d")
            try bytes.write(to: url)
            XCTAssertThrowsError(try A3DParser().parse(url: url))
        }
    }

    private func temporaryURL(extension ext: String) -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString).appendingPathExtension(ext)
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }

    private func archive(_ files: [String: Data]) throws -> URL {
        let directory = temporaryURL(extension: "fixture")
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        for (name, data) in files {
            let url = directory.appendingPathComponent(name)
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try data.write(to: url)
        }
        let output = temporaryURL(extension: "a3d")
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/zip")
        process.arguments = ["-q", "-r", output.path, "."]
        process.currentDirectoryURL = directory
        try process.run()
        process.waitUntilExit()
        XCTAssertEqual(process.terminationStatus, 0)
        return output
    }
}
