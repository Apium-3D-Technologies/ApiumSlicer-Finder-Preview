    ; filament_type = PEEK
    ; nozzle_diameter = 0.4
    ; temperature = 400
    ; bed_temperature = 150
    ; layer_height = 0.2
    ; perimeters = 3
    ; fill_pattern = gyroid
    ; fill_density = 25%
    ; apiumslicer_config = end
    """
    private let png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLttAAAAABJRU5ErkJggg=="

    func testSparseGCodeReadsStayBounded() throws {
        let header = "; generated by ApiumSlicer 1.0\n; printer_model = HEADER\n"
        let footer = "\n; estimated printing time (normal mode) = 1h 2m\n" + config
            + "\n; thumbnail_PNG begin 1x1 96\n; \(png)\n; thumbnail_PNG end\n"
        for size: UInt64 in [1024 * 1024 * 1024, 6 * 1024 * 1024 * 1024] {
            var bytesRead = 0
            let metadata = try GCodeParser().parse(size: size) { offset, count in
                XCTAssertTrue(offset < 1024 * 1024 || offset >= size - 8 * 1024 * 1024)
                bytesRead += count
                var data = Data(repeating: 32, count: count)
                if offset == 0 { data.replaceSubrange(0..<header.utf8.count, with: header.utf8) }
                if offset + UInt64(count) == size {
                    data.replaceSubrange((count - footer.utf8.count)..<count, with: footer.utf8)
                }
                return data
            }
            XCTAssertTrue(metadata.isApiumFile)
            XCTAssertEqual(metadata.printer, "P400")
            XCTAssertEqual(metadata.printTime, "1h 2m")
            XCTAssertNotNil(metadata.previewImage)
            XCTAssertEqual(bytesRead, 64 * 1024)
        }
    }

    func testMissingFooterAndImageNeverCauseFullScan() throws {
        let header = "; generated by ApiumSlicer 1.0\n; printer_model = HEADER\n"
        let size: UInt64 = 6 * 1024 * 1024 * 1024
        var bytesRead = 0
        let metadata = try GCodeParser().parse(size: size) { offset, count in
            XCTAssertTrue(offset == 0 || offset >= size - 8 * 1024 * 1024)
            bytesRead += count
            var data = Data(repeating: 32, count: count)
            if offset == 0 { data.replaceSubrange(0..<header.utf8.count, with: header.utf8) }
            return data
        }
        XCTAssertTrue(metadata.isApiumFile)
        XCTAssertEqual(metadata.printer, "HEADER")
        XCTAssertNil(metadata.previewImage)
        XCTAssertLessThanOrEqual(bytesRead, 9 * 1024 * 1024)
    }

    func testThumbnailCrossingInitialWindowAndFooterPrecedence() throws {
        let text = "; generated by ApiumSlicer 1.0\n; printer_model = HEADER\n"
            + String(repeating: "G1 X0 Y0\n", count: 20_000) + config
            + "\n" + String(repeating: " ", count: 64 * 1024 - 20)
            + "\n; thumbnail_PNG begin 1x1 96\n; \(png)\n; thumbnail_PNG end\n"
        let data = Data(text.utf8)
        let metadata = try GCodeParser().parse(size: UInt64(data.count)) { offset, count in
            data.subdata(in: Int(offset)..<(Int(offset) + count))
        }
        XCTAssertTrue(metadata.isApiumFile)
        XCTAssertEqual(metadata.printer, "P400")
        XCTAssertNotNil(metadata.previewImage)
    }

    func testLegacyHeaderThumbnailAndMalformedFooterImage() throws {
        let text = "; generated by ApiumSlicer\n; thumbnail begin 1x1 96\n; \(png)\n; thumbnail end\n"
            + String(repeating: "G1 X0 Y0\n", count: 20_000) + config
            + "\n; thumbnail_PNG begin 1x1 4\n; YWJj\n; thumbnail_PNG end\n"
        let data = Data(text.utf8)
        let metadata = try GCodeParser().parse(size: UInt64(data.count)) { offset, count in
            data.subdata(in: Int(offset)..<(Int(offset) + count))
        }
        XCTAssertNotNil(metadata.previewImage)
        XCTAssertEqual(metadata.printer, "P400")
    }

    func testRangeReadErrorIsPropagated() {
