import XCTest
@testable import ApiumQuickLookShared

final class GCodeParserTests: XCTestCase {
    func testParsesApiumGCodeWithThumbnailAndFields() throws {
        let metadata = try GCodeParser().parse(url: FixturePaths.gcodeURL)

        XCTAssertTrue(metadata.isApiumFile)
        XCTAssertNotNil(metadata.previewImage)
        XCTAssertEqual(metadata.printer, "P220_T0")
        XCTAssertEqual(metadata.materialType, "PLA")
        XCTAssertEqual(metadata.nozzleDiameter, "0.4")
        XCTAssertEqual(metadata.printTime, "2h 11m 42s")
    }

    func testNonApiumGCodeIsRejected() throws {
        let temp = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("non_apium_test.gcode")
        let sample = """
        ; generated by AnotherSlicer
        ; printer_model = Generic
        G1 X0 Y0
        """
        try sample.write(to: temp, atomically: true, encoding: .utf8)

        let metadata = try GCodeParser().parse(url: temp)
        XCTAssertFalse(metadata.isApiumFile)
    }

    func testFallbackKeysForGCode() throws {
        let temp = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("fallback_test.gcode")
        let sample = """
        ; generated by ApiumSlicer 1.0
        ; printer_settings_id = ApiumPrinterFallback
        ; filament_settings_id = Apium PLA (Glass)
        ; printer_variant = 0.6
        ; estimated printing time = 1h 01m 02s
        ; apiumslicer_config = begin
        ; apiumslicer_config = end
        """
        try sample.write(to: temp, atomically: true, encoding: .utf8)

        let metadata = try GCodeParser().parse(url: temp)
        XCTAssertTrue(metadata.isApiumFile)
        XCTAssertEqual(metadata.printer, "ApiumPrinterFallback")
        XCTAssertEqual(metadata.materialType, "Apium PLA (Glass)")
        XCTAssertEqual(metadata.nozzleDiameter, "0.6")
        XCTAssertEqual(metadata.printTime, "1h 01m 02s")
    }

    func testApiumGCodeWithoutThumbnailReturnsNoImage() throws {
        let temp = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("no_thumbnail_test.gcode")
        let sample = """
        ; generated by ApiumSlicer 1.0
        ; printer_model = P220_T0
        ; filament_type = PLA
        ; nozzle_diameter = 0.4
        ; estimated printing time (normal mode) = 2h 00m 00s
        ; apiumslicer_config = begin
        ; apiumslicer_config = end
        """
        try sample.write(to: temp, atomically: true, encoding: .utf8)

        let metadata = try GCodeParser().parse(url: temp)
        XCTAssertTrue(metadata.isApiumFile)
        XCTAssertNil(metadata.previewImage)
        XCTAssertEqual(metadata.printer, "P220_T0")
    }
}
